"""
Shared prompt / completion construction for SFT (Day 4-5).

One place that defines how a converted floor-plan JSON (data/processed/*.jsonl,
project schema — see docs/PROJECT_CONTEXT.md) is turned into an
instruction-tuning example, so `prepare_sft_data.py`, `train_qlora.py`, and
`eval_json_validity.py` all agree byte-for-byte on the prompt.

Split (confirmed with user, Day 4-5):

  PROMPT  = task instruction + input JSON:
              {"boundary": {"polygon": [...], "entrance": [x, y]},
               "rooms":    [{"type": ..., "target_area": <m^2>}, ...]}
            `target_area` is the *spec* field (PROJECT_CONTEXT.md §2, "rooms
            (id, type, polygon, target area)"); the ResPlan converter does not
            emit it, so it is recomputed here from each room polygon's area.

  COMPLETION = the generated part of the plan JSON:
              {"boundary": {...echoed...},
               "rooms":    [{"id", "type", "polygon"}, ...],
               "openings": [{"id", "type", "host_wall", "endpoints",
                             "clear_width", "swing"}, ...]}

  NOT generated by the model (templated / computed downstream):
    - metadata  : fixed boilerplate — schema version, units, jurisdiction
                  placeholder tag, occupancy. `template_metadata()`.
    - relations : fully derivable from `openings` (every door -> via_door, or
                  `direct` if it meets the exterior). `relations_from_openings()`
                  — identical rule to data/convert.py.
    - audit     : always `[]` in a generated plan; the verifier bank computes its
                  own records and never writes back into the plan.

`reconstruct_plan()` glues a model-generated completion object back together with
the templated pieces into a full project-schema plan the verifier bank can read.

Clause thresholds referenced anywhere downstream are a PLACEHOLDER / generic code,
not a real jurisdiction (see docs/LIMITATIONS.md).
"""

from __future__ import annotations

import json
from typing import Any

from shapely.geometry import Polygon

SCHEMA_VERSION = "0.1"
JURISDICTION = "placeholder/generic — not a real jurisdiction"

# Room-type order used when listing rooms in the prompt. Matches data/convert.py's
# _ROOM_KEYS so the prompt's room order lines up with the converted plan's.
_ROOM_TYPE_ORDER = ("living", "bedroom", "bathroom", "kitchen", "storage", "balcony")

SYSTEM_PROMPT = (
    "You are a floor-plan generator. You are given a building boundary polygon, an "
    "entrance point on that boundary, and a list of rooms to place with their target "
    "floor areas in square metres. Produce a single-floor residential layout as one "
    "JSON object with exactly these keys: \"boundary\" (echo the given polygon and "
    "entrance unchanged), \"rooms\" (one object per requested room, in the given "
    "order, each with \"id\", \"type\", and a \"polygon\" as a list of [x, y] vertex "
    "pairs in metres), and \"openings\" (doors and windows, each with \"id\", "
    "\"type\", \"host_wall\", \"endpoints\", \"clear_width\", \"swing\"). Rooms must "
    "be simple, non-overlapping polygons inside the boundary. Every room must be "
    "reachable from the entrance through doors. Output only the JSON object, no prose. "
    "Any building-code thresholds are a placeholder/generic code, not a real "
    "jurisdiction."
)

# Compact JSON: no spaces, stable key order (we build dicts in the wanted order).
_COMPACT = dict(separators=(",", ":"), ensure_ascii=False)


# ── prompt side ──────────────────────────────────────────────────────────────

def _room_target_area(room: dict[str, Any]) -> float:
    poly = Polygon([tuple(p) for p in room.get("polygon", [])])
    return round(poly.area, 1) if poly.is_valid and poly.area > 0 else 0.0


def build_input_obj(plan: dict[str, Any]) -> dict[str, Any]:
    """The JSON object shown to the model inside the user turn."""
    return {
        "boundary": {
            "polygon": plan["boundary"]["polygon"],
            "entrance": plan["boundary"]["entrance"],
        },
        "rooms": [
            {"type": r["type"], "target_area": _room_target_area(r)}
            for r in plan["rooms"]
        ],
    }


def build_messages(plan: dict[str, Any]) -> list[dict[str, str]]:
    """Chat messages up to (not including) the assistant answer."""
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": json.dumps(build_input_obj(plan), **_COMPACT)},
    ]


def build_prompt_text(plan: dict[str, Any], tokenizer) -> str:
    """
    Rendered prompt string, ending with the assistant generation prefix, using the
    model's own chat template. `train_qlora.py` and `eval_json_validity.py` both
    call this so the training prefix and the inference prefix are identical.
    """
    return tokenizer.apply_chat_template(
        build_messages(plan), tokenize=False, add_generation_prompt=True
    )


# ── completion side ──────────────────────────────────────────────────────────

def build_completion_obj(plan: dict[str, Any]) -> dict[str, Any]:
    """The part of the plan the model is trained to produce."""
    return {
        "boundary": {
            "polygon": plan["boundary"]["polygon"],
            "entrance": plan["boundary"]["entrance"],
        },
        "rooms": [
            {"id": r["id"], "type": r["type"], "polygon": r["polygon"]}
            for r in plan["rooms"]
        ],
        "openings": [
            {
                "id": o["id"],
                "type": o["type"],
                "host_wall": o["host_wall"],
                "endpoints": o["endpoints"],
                "clear_width": o["clear_width"],
                "swing": o["swing"],
            }
            for o in plan["openings"]
        ],
    }


def build_completion_text(plan: dict[str, Any]) -> str:
    return json.dumps(build_completion_obj(plan), **_COMPACT)


# ── downstream reassembly (templated / derived pieces) ───────────────────────

def template_metadata() -> dict[str, Any]:
    """
    Fixed boilerplate metadata for a generated plan (PROJECT_CONTEXT.md §2:
    schema version, scale, jurisdiction/edition, occupancy). Not learned by the
    model — stamped on deterministically.
    """
    return {
        "schema_version": SCHEMA_VERSION,
        "units": "meters",
        "jurisdiction": JURISDICTION,
        "occupancy": "residential",
    }


def relations_from_openings(openings: list[dict[str, Any]]) -> dict[str, Any]:
    """
    Rebuild `relations.derived` from openings. Same rule as data/convert.py:
    one entry per door-type opening — `direct` if it meets the exterior, else
    `via_door`. Windows contribute nothing.
    """
    derived: list[dict[str, Any]] = []
    for o in openings:
        if o.get("type") != "door":
            continue
        hw = o.get("host_wall", [])
        if len(hw) != 2:
            continue
        derived.append(
            {"type": "direct" if hw[0] == "exterior" else "via_door", "rooms": list(hw)}
        )
    return {"derived": derived}


def reconstruct_plan(completion_obj: dict[str, Any]) -> dict[str, Any]:
    """
    Full project-schema plan from a model-generated completion object, so the
    verifier bank (geometry_gate, topology, ...) can consume it.

    Raises KeyError / TypeError if `completion_obj` is missing the generated keys
    — callers treat that as "generated an invalid plan".
    """
    openings = completion_obj["openings"]
    return {
        "metadata": template_metadata(),
        "boundary": completion_obj["boundary"],
        "rooms": completion_obj["rooms"],
        "openings": openings,
        "relations": relations_from_openings(openings),
        "audit": [],
    }
